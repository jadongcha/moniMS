    // ---------- 적용 → 복원 (임시 폴더를 %LOCALAPPDATA% / %APPDATA% 로 사용) ----------

    [Fact]
    public async Task Applies_terminal_and_discord_then_restores_exactly()
    {
        var local = Path.Combine(_root, "Local");
        var roaming = Path.Combine(_root, "Roaming");

        // Terminal: 스토어 버전은 기존 설정 있음, Preview는 아직 한 번도 안 켬
        var stable = Path.Combine(local, "Packages", "Microsoft.WindowsTerminal_8wekyb3d8bbwe", "LocalState", "settings.json");
        var preview = Path.Combine(local, "Packages", "Microsoft.WindowsTerminalPreview_8wekyb3d8bbwe", "LocalState", "settings.json");
        Directory.CreateDirectory(Path.GetDirectoryName(stable)!);
        Directory.CreateDirectory(Path.Combine(local, "Packages", "Microsoft.WindowsTerminalPreview_8wekyb3d8bbwe"));
        File.WriteAllText(stable, UserTerminalSettings);

        // Discord: Vencord(설정 있음) + BetterDiscord(설치 직후)
        var vencordSettings = Path.Combine(roaming, "Vencord", "settings", "settings.json");
        Directory.CreateDirectory(Path.GetDirectoryName(vencordSettings)!);
        const string vencordOriginal = """{ "plugins": { "x": { "enabled": true } }, "enabledThemes": ["mine.css"] }""";
        File.WriteAllText(vencordSettings, vencordOriginal);
        Directory.CreateDirectory(Path.Combine(roaming, "BetterDiscord"));

        var library = new ThemeLibrary(Path.Combine(_root, "lib"));
        var package = await new ThemeImporter(library).ImportAsync(MakePackage());
        Assert.Equal(2, package.Apps.Count);

        var storage = new ShellThemeTests.FakeStorage();
        var targets = new AppThemeTargets(local, roaming, _ => true);
        var applier = new ThemeApplier(storage, new ShellThemeTests.DirectWriter(storage), new ShellThemeTests.NoWallpaper(), library,
            targets: targets);

        var result = applier.Apply(package, new ThemeApplyOptions([], false, null, [AppThemeKind.WindowsTerminal, AppThemeKind.Discord]));

        Assert.Empty(result.AppliedMods);
        Assert.Contains("Windows Terminal", result.Apps);
        Assert.Contains("Discord (Vencord, BetterDiscord)", result.Apps);

        var stableNow = Parse(File.ReadAllText(stable));
        Assert.Equal("Gruvbox Material", stableNow["profiles"]!["defaults"]!["colorScheme"]!.GetValue<string>());
        Assert.True(File.Exists(preview));

        Assert.True(File.Exists(Path.Combine(roaming, "Vencord", "themes", "sample.theme.css")));
        var enabled = Parse(File.ReadAllText(vencordSettings))["enabledThemes"]!.AsArray().Select(e => e!.GetValue<string>());
        Assert.Equal(["mine.css", "sample.theme.css"], enabled);
        Assert.True(Parse(File.ReadAllText(vencordSettings))["plugins"]!["x"]!["enabled"]!.GetValue<bool>());
        var bdState = Path.Combine(roaming, "BetterDiscord", "data", "stable", "themes.json");
        Assert.True(Parse(File.ReadAllText(bdState))["Sample Theme"]!.GetValue<bool>());

        Assert.True(applier.HasBackup);
        var restored = applier.RestoreLatest();
        Assert.Equal(["Discord", "Windows Terminal"], restored.Order());

        // 원래 있던 파일은 글자 하나까지 그대로, 없던 파일은 삭제
        Assert.Equal(UserTerminalSettings, File.ReadAllText(stable));
        Assert.Equal(vencordOriginal, File.ReadAllText(vencordSettings));
        Assert.False(File.Exists(preview));
        Assert.False(File.Exists(Path.Combine(roaming, "Vencord", "themes", "sample.theme.css")));
        Assert.False(File.Exists(bdState));
        Assert.False(applier.HasBackup);
    }

    [Fact]
    public async Task Missing_apps_are_skipped_with_a_warning_and_no_backup()
    {
        var library = new ThemeLibrary(Path.Combine(_root, "lib"));
        var package = await new ThemeImporter(library).ImportAsync(MakePackage());
        var storage = new ShellThemeTests.FakeStorage();
