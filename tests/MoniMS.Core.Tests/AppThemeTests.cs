        Assert.Empty(result.Apps);
        Assert.Contains(result.Warnings, w => w.Contains("Windows Terminal is not installed"));
        Assert.Contains(result.Warnings, w => w.Contains("Vencord"));
        Assert.False(applier.HasBackup);
    }

    [Fact]
    public async Task Old_manifest_is_rescanned_for_app_themes()
    {
        var library = new ThemeLibrary(Path.Combine(_root, "lib"));
        var package = await new ThemeImporter(library).ImportAsync(MakePackage());

        // 예전 버전이 저장한 매니페스트 흉내: schemaVersion 1, apps 없음
        var manifest = Path.Combine(package.Directory, "theme.json");
        var json = JsonNode.Parse(File.ReadAllText(manifest))!.AsObject();
        json["schemaVersion"] = 1;
        json.Remove("apps");
        File.WriteAllText(manifest, json.ToJsonString());

        var loaded = Assert.Single(library.GetAll());
        Assert.Equal(2, loaded.Apps.Count);
        Assert.Equal(ThemePackage.CurrentSchemaVersion, loaded.SchemaVersion);
        Assert.Contains("\"apps\"", File.ReadAllText(manifest)); // 다시 저장됨
    }

    private sealed class RecordingWallpaper : IWallpaperService
    {
        public string Current { get; set; } = "original.jpg";

        public WallpaperSettings Capture(string d) =>
            new() { Monitors = [new MonitorWallpaper { ImageFile = Current }] };

        public void Apply(WallpaperSettings s, string d) => Current = s.Monitors[0].ImageFile!;
        public void SetForAllMonitors(string p, WallpaperPosition pos) => Current = Path.GetFileName(p);
    }

    [Fact]
    public async Task Reset_to_original_undoes_every_apply_at_once()
    {
        var local = Path.Combine(_root, "Local");
        var stable = Path.Combine(local, "Packages", "Microsoft.WindowsTerminal_8wekyb3d8bbwe", "LocalState", "settings.json");
        Directory.CreateDirectory(Path.GetDirectoryName(stable)!);
        File.WriteAllText(stable, UserTerminalSettings);

        var library = new ThemeLibrary(Path.Combine(_root, "lib"));
        var package = await new ThemeImporter(library).ImportAsync(MakePackage());
        Directory.CreateDirectory(Path.Combine(package.FilesDirectory, "wallpapers"));
        var wp = Path.Combine("wallpapers", "theme.png");
        File.WriteAllText(package.FullPath(wp), "png");

        var storage = new ShellThemeTests.FakeStorage();
        var wallpaper = new RecordingWallpaper();
        var applier = new ThemeApplier(storage, new ShellThemeTests.DirectWriter(storage), wallpaper, library,
            targets: new AppThemeTargets(local, Path.Combine(_root, "Roaming"), _ => true));
        Assert.False(applier.HasOriginal);

        // 테마를 두 번 적용: 두 번째 백업에는 "첫 테마가 적용된 상태"가 들어간다
        var options = new ThemeApplyOptions([WindhawkMods.TaskbarStyler], false, null, [AppThemeKind.WindowsTerminal]);
        package.Mods.Add(new ThemeModConfig { ModId = WindhawkMods.TaskbarStyler, SourceFile = "taskbar.json" });
        File.WriteAllText(package.FullPath("taskbar.json"), """{ "theme": "", "controlStyles[0].target": "Taskbar.TaskbarFrame" }""");
        applier.Apply(package, options);
        Assert.Equal("Taskbar.TaskbarFrame", storage.Mods[WindhawkMods.TaskbarStyler]["controlStyles[0].target"]);
        Thread.Sleep(5);
        applier.Apply(package, options);
        Assert.True(applier.ApplyWallpaper(package, wp));
        Assert.True(applier.ApplyWallpaper(package, wp)); // 두 번째는 원래 배경화면을 덮어쓰지 않아야 함
        Assert.Equal("theme.png", wallpaper.Current);
        Assert.True(applier.HasOriginal);

        var restored = applier.ResetToOriginal();
        Assert.True(applier.RestoreOriginalWallpaper());

        Assert.Equal(UserTerminalSettings, File.ReadAllText(stable)); // 첫 적용 전 내용
        Assert.Equal("1", Assert.Single(storage.Mods[WindhawkMods.TaskbarStyler]).Value); // 첫 적용 전 값 {old: "1"}
        Assert.Contains("Windows Terminal", restored);
        Assert.Equal("original.jpg", wallpaper.Current);
        Assert.False(applier.HasBackup);
        Assert.False(applier.HasOriginal);
    }

    private string MakePackage()
    {
        var dir = Path.Combine(_root, "MyPack");
        Directory.CreateDirectory(Path.Combine(dir, "Terminal"));
        Directory.CreateDirectory(Path.Combine(dir, "Discord"));
        File.WriteAllText(Path.Combine(dir, "Terminal", "settings.json"), TerminalSource);
        File.WriteAllText(Path.Combine(dir, "Discord", "sample.theme.css"), "/**\n * @name Sample Theme\n */\nbody { color: red; }");
        return dir;
    }
