    private static JsonObject Parse(string text) => (JsonObject)JsonText.Parse(text)!;

    private static IEnumerable<string?> SchemeNames(JsonObject o) =>
        ((JsonArray)o["schemes"]!).Select(s => s!["name"]!.GetValue<string>());

    // ---------- Windows Terminal ----------

    [Fact]
    public void Terminal_merge_keeps_personal_settings_and_replaces_schemes_by_name()
    {
        var target = Parse(UserTerminalSettings);
        var source = WindowsTerminalThemer.Normalize(Parse(TerminalSource))!;
        var warnings = new List<string>();

        WindowsTerminalThemer.Merge(target, source, _ => true, warnings);

        // 같은 이름(대소문자 무시)은 교체, 내 구성표는 유지, 새 구성표는 추가
        Assert.Equal(["Gruvbox Material", "My Scheme", "Monochrome"], SchemeNames(target));
        Assert.Equal("#272E33", target["schemes"]![0]!["background"]!.GetValue<string>());

        // 개인 설정은 그대로, 패키지의 기본 프로필/단축키는 가져오지 않음
        Assert.Equal("{61c54bbd-c2c6-5271-96e7-009a87ff44bf}", target["defaultProfile"]!.GetValue<string>());
        Assert.NotNull(target["actions"]);
        Assert.Null(target["keybindings"]);

        // 예전 배열 형식 profiles → { defaults, list }
        var profiles = (JsonObject)target["profiles"]!;
        Assert.Equal(2, ((JsonArray)profiles["list"]!).Count);
        var defaults = (JsonObject)profiles["defaults"]!;
        Assert.Equal("Gruvbox Material", defaults["colorScheme"]!.GetValue<string>());
        Assert.Equal(80, defaults["opacity"]!.GetValue<int>());
        Assert.Equal("JetBrainsMono Nerd Font", defaults["font"]!["face"]!.GetValue<string>());
        Assert.Null(defaults["antialiasingMode"]); // 모양 화이트리스트 밖

        // 정의된 창 테마가 아니면 theme은 건드리지 않음, 탭 줄 아크릴은 가져옴
        Assert.Null(target["theme"]);
        Assert.True(target["useAcrylicInTabRow"]!.GetValue<bool>());
        Assert.Single(target["themes"]!.AsArray());

        // Ubuntu는 자기 구성표가 있어 바뀌지 않음 → 알림
        Assert.Contains(warnings, w => w.Contains("Ubuntu"));
    }

    [Fact]
    public void Terminal_merge_skips_missing_font_but_keeps_my_font_size()
    {
        var target = Parse("""{ "profiles": { "defaults": { "font": { "face": "Cascadia Mono", "size": 13 } }, "list": [] } }""");
        var source = WindowsTerminalThemer.Normalize(Parse(TerminalSource))!;
        var warnings = new List<string>();

        WindowsTerminalThemer.Merge(target, source, _ => false, warnings);

        var font = target["profiles"]!["defaults"]!["font"]!;
        Assert.Equal("Cascadia Mono", font["face"]!.GetValue<string>());
        Assert.Equal(13, font["size"]!.GetValue<int>());
        Assert.Contains(warnings, w => w.Contains("JetBrainsMono Nerd Font"));
    }

    [Fact]
    public void Terminal_single_scheme_file_is_accepted_and_other_json_is_not()
    {
        var single = WindowsTerminalThemer.Normalize(Parse(
            """{ "name": "Dracula", "background": "#282A36", "foreground": "#F8F8F2", "black": "#21222C" }"""));
        Assert.NotNull(single);
        Assert.Equal("Dracula", WindowsTerminalThemer.PreferredScheme(single!));
        Assert.Equal("color scheme 'Dracula'", WindowsTerminalThemer.Summarize(single!));

        Assert.Null(WindowsTerminalThemer.Normalize(Parse("""{ "profiles": { "list": [] } }""")));
        Assert.Null(WindowsTerminalThemer.Normalize(Parse("""{ "bar": { "height": 30 } }"""))); // komorebi.json 같은 것
    }

